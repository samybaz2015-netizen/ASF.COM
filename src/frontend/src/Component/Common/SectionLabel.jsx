import "./SectionLabel.css";

/**
 * عنوان قسم داخل نماذج أوامر العمل.
 *
 * كان كل نموذج يعرّف نسخته الخاصة بلون مكتوب في الكود — أزرق هنا وأصفر هناك
 * وأخضر في ثالث — فاختلف شكل الشاشة الواحدة عن أختها، وأيّ تغيير في اللون
 * كان يقتضي تتبّع خمسة ملفات. صار التعريف واحداً واللون من رمز الرأس الموحّد،
 * فما يُغيَّر مرّةً يسري على كل الأنواع وكل الصفحات — الحالية والقادمة.
 *
 * الوسيط `color` يُقبل ويُهمل: النماذج القديمة تمرّره، وحذفه من نداءاتها كلها
 * تغييرٌ واسع بلا فائدة، وإبقاؤه يتركها تعمل بلا تعديل.
 */
export function SectionLabel({ children, split = false }) {
  // `split` لعنوانٍ يحمل إجراءً أو عدّاداً في طرفه الآخر.
  return (
    <div className={"asf-section-label" + (split ? " asf-section-label--split" : "")}>
      {children}
    </div>
  );
}

export default SectionLabel;
